# 이름에 브랜드 글자가 들어 있는가. ^글자: 이름 맨 앞에 있을 때만. 글자!뒷글자: 바로 뒤에 뒷글자가 오면 아니다.
def pat_in(n, p):
    head = p[0] == '^'
    if head:
        p = p[1:]
    p, _, nx = p.partition('!')
    if head:
        return n.startswith(p) and not (nx and n[len(p):].startswith(nx))
    i = n.find(p)
    while i >= 0:
        if not nx or not n[i + len(p):].startswith(nx):
            return True
        i = n.find(p, i + 1)
    return False


